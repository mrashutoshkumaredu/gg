def hindi_lines(task):
    """Instruction lines paired with Hindi: [(english, hindi or None, is_quote)]."""
    hi = HI.get(task.id, [])
    out, k = [], 0
    for line in task.instructions:
        if line.startswith("   "):
            out.append((line.strip(), None, True))
        else:
            out.append((line, hi[k] if k < len(hi) else None, False))
            k += 1
    return out
