def _percent_book(path):
    from openpyxl import Workbook
    wb = Workbook()
    ws = wb.active
    ws.append(["Item", "Price", "Tax", "", "Rate", 0.18])
    for r in [("Pen", 100), ("Bag", 850), ("Lamp", 1200), ("Mat", 300), ("Cup", 150)]:
        ws.append(list(r))
    wb.save(str(path))



def _hdr_missing(ctx, name):
    ws = ctx.excel().ws(None, values=True)
    heads = [str(c.value) for row in ws.iter_rows(min_row=1, max_row=2) for c in row if c.value is not None]
    return (name not in heads), "Headings: " + ", ".join(heads)


